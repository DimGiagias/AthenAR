// Download the City's municipal culture venues (museums, galleries, theatres,
// the cinema, libraries) for the passport rewards into src/data/cultureVenues.ts:
//
//   node scripts/fetch-culture-venues.mjs
//
// The result is committed, so this only needs re-running to refresh the venues.
// Source: the City of Athens open data portal (opendata.cityofathens.gr, the
// source the Apps4Athens hackathon points to), dataset «Χώροι πολιτισμού Δήμου
// Αθηναίων», CC BY 4.0. The dataset is found through the portal's CKAN API; the
// portal lists it as a layer of the City's GIS server, which serves the venues.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const file = path.join(root, 'src/data/cultureVenues.ts');

const PORTAL = 'https://opendata.cityofathens.gr';
const TITLE = 'Χώροι πολιτισμού Δήμου Αθηναίων';

/** Slips in the City's data, by venue id. */
const VENUE_FIXES = {
    170: { address: 'Τενέδου 34, Κυψέλη' }, // starts with a Latin T
    230: { address: 'Λόφος Λυκαβηττού' }, // listed at its operator's address (Technopolis)
};

const getJson = async (url) => {
    const res = await fetch(url, { signal: AbortSignal.timeout(120000) });
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    return res.json();
};

const search = await getJson(`${PORTAL}/api/3/action/package_search?q=${encodeURIComponent(`"${TITLE}"`)}&rows=20`);
const pkg = search.result.results.find((p) => p.title.trim() === TITLE);
if (!pkg) throw new Error(`"${TITLE}" not found on ${PORTAL}`);

// e.g. a WMS resource "http://gis.cityofathens.gr/geoserver/wms#geonode:politismos24_f"
const [server, layer] = pkg.resources.find((r) => String(r.format).toUpperCase() === 'WMS')?.url.split('#') ?? [];
if (!server || !layer) throw new Error(`no GIS layer listed for "${TITLE}"`);
const source = { title: TITLE, url: `${PORTAL}/dataset/${pkg.name}`, updated: String(pkg.metadata_modified).slice(0, 10) };
console.log(`${source.url} -> ${layer}`);

const wfs = `${server.replace(/\/wms$/, '/ows')}?service=WFS&version=1.0.0&request=GetFeature&outputFormat=json&srsName=EPSG%3A4326&typename=${encodeURIComponent(layer)}`;
const { features } = await getJson(wfs);
const venues = features
    .map((f) => {
        let point = f.geometry.coordinates;
        while (Array.isArray(point[0])) point = point[0];
        const p = f.properties;
        return {
            id: p.fid,
            type: p.type.trim(),
            // "Μουσείο, Λαϊκής Τέχνης…" -> "Μουσείο Λαϊκής Τέχνης…"
            name: p.name.replace(/\s+/g, ' ').trim().replace(/^((?:Ψηφιακό )?Μουσείο), /, '$1 '),
            address: (p.tax_diefth ?? '').replace(/,?\s*Τ\.?\s*Κ\.?.*$/, '').trim(),
            lat: Math.round(point[1] * 1e5) / 1e5,
            lng: Math.round(point[0] * 1e5) / 1e5,
            link: p.link_ ?? '',
            ...VENUE_FIXES[p.fid],
        };
    })
    .sort((a, b) => a.id - b.id);

fs.writeFileSync(
    file,
    `// Generated by scripts/fetch-culture-venues.mjs; edit the script, not this file.\n` +
        `// City of Athens open data portal: «${TITLE}», found through its CKAN API (${layer}).\n` +
        `import type { CultureVenue } from './culture';\n\n` +
        `/** The dataset on the City's open data portal. */\n` +
        `export const CULTURE_SOURCE = ${JSON.stringify(source, null, 4)} as const;\n\n` +
        `export const CULTURE_VENUES: readonly CultureVenue[] = ${JSON.stringify(venues, null, 4)};\n`,
);
console.log(`${venues.length} venues -> ${path.relative(root, file)}`);
